func TestAtofMatchesGlibc(t *testing.T) {
	for _, c := range atofCases {
		d := Atof(c.in)
		if math.Float64bits(d) != c.d {
			t.Errorf("Atof(%q) = %#016x, want %#016x", c.in, math.Float64bits(d), c.d)
		}
		if f := math.Float32bits(float32(d)); f != c.f {
			t.Errorf("float(Atof(%q)) = %#08x, want %#08x", c.in, f, c.f)
		}
		if a := Atoi(c.in); a != c.atoi {
			t.Errorf("Atoi(%q) = %d, want %d", c.in, a, c.atoi)
		}
	}
}

func TestStrtodConsumed(t *testing.T) {
	cases := []struct {
		in string
		n  int
	}{
		{"", 0}, {"abc", 0}, {"  1.5x", 5}, {"1e", 1}, {"1e+5", 4}, {"0x", 1}, {"0x1p", 3},
		{"infinity!", 8}, {"infinit", 3}, {"nan(12)z", 7}, {"nan(", 3}, {"-.5", 3}, {".", 0},
	}
	for _, c := range cases {
		if _, n := Strtod(c.in); n != c.n {
			t.Errorf("Strtod(%q) consumed %d, want %d", c.in, n, c.n)
		}
	}
}
